"""Developer-only: derive relocation-tolerant fingerprints from the audited copy.

The generated header contains hashes, short entry anchors, and relocation slots,
not complete game functions. Normalization preserves internal branches, member
offsets, enum values and instruction selection. No game input is needed to build.
"""
import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts/python-deps'))
import capstone
from capstone.x86 import X86_OP_IMM, X86_OP_MEM, X86_REG_RIP
import pefile

FUNCTIONS = {'SHOT': 6341872, 'READY': 4457500, 'IDENTITY': 5071268, 'RELATION': 37060763, 'AIM': 10906710, 'CONTROLLER': 37954822, 'PAWN': 49858870, 'FOCUS': 112650834, 'WEAK': 39194120, 'FOCUS_ACCESSOR': 34139752, 'PAWN_WITNESS': 91024100, 'CAPSULE_CLASS': 7977220, 'CAPSULE_CTOR': 11996410, 'CAPSULE_DIMS': 18800082, 'CAPSULE_POINTER': 15565764, 'SCENE_SCALE': 122086358, 'AIM_TRANSFORM': 10906890, 'TICK': 5293068, 'COOKIE': 42163504}
LEAVES = {0x2f8c936:20,0x2560e08:84,0x208ee68:15}
GLOBALS = {0xa0e68d0:0,0xa0e68e4:1,0x9eec140:2,0xa234940:3}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('executable', type=Path)
    args = parser.parse_args()
    raw = args.executable.read_bytes()
    # Fingerprints must be reviewed again before accepting a new compiler layout.
    assert hashlib.sha256(raw).hexdigest() == '61bc1e030740cebc30cf1dad0c86cf65e39e12ff0500225821d684181e08d56b'
    pe = pefile.PE(data=raw,fast_load=True)
    pe.parse_data_directories(directories=[3])
    base = pe.OPTIONAL_HEADER.ImageBase
    ends = {e.struct.BeginAddress: e.struct.EndAddress for e in pe.DIRECTORY_ENTRY_EXCEPTION}
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    md.detail = True
    names = list(FUNCTIONS)
    profiles, edges, globals_ = [], [], []
    byte_array = lambda values: '{' + ','.join(str(v) for v in values) + '}'
    lines = ['/* Generated by scripts/make_address_profile.py; reviewed x64 layout. */', '#pragma once']
    for idx, (name, start) in enumerate(FUNCTIONS.items()):
        end = start+LEAVES[start] if start in LEAVES else ends[start]
        data = bytearray(pe.get_data(start, end-start))
        normalized = bytearray(data)
        masks = []
        consumed = 0
        for ins in md.disasm(bytes(data), base + start):
            consumed += ins.size
            off = ins.address - base - start
            for operand in ins.operands:
                if operand.type == X86_OP_MEM and operand.mem.base == X86_REG_RIP:
                    # RIP-relative displacement is always signed disp32. Some Capstone
                    # builds misreport disp_size for operand-size-prefixed SSE.
                    assert int.from_bytes(ins.bytes[ins.disp_offset:ins.disp_offset+4],'little',signed=True)==ins.disp
                    masks.append((off + ins.disp_offset, 4))
                    target = ins.address + ins.size + ins.disp - base
                    if target in GLOBALS:
                        globals_.append((idx, off + ins.disp_offset, off + ins.size, GLOBALS[target]))
                    if target in FUNCTIONS.values():
                        edges.append((idx,off+ins.disp_offset,off+ins.size,list(FUNCTIONS.values()).index(target)))
                    if name=='CAPSULE_CLASS' and ins.address-base==0x79b9b8:
                        literal_ref=(idx,off+ins.disp_offset,off+ins.size,0)
                        literal=pe.get_data(target,len('CapsuleComponent')*2+2)
                        assert literal=='CapsuleComponent\0'.encode('utf-16le')
                elif operand.type == X86_OP_IMM and (ins.group(capstone.CS_GRP_CALL) or ins.group(capstone.CS_GRP_JUMP)):
                    target = operand.imm - base
                    if not start <= target < end:
                        assert ins.imm_size == 4, (name, ins.mnemonic)
                        masks.append((off + ins.imm_offset, 4))
                        if target in FUNCTIONS.values():
                            edges.append((idx, off + ins.imm_offset, off + ins.size,
                                          list(FUNCTIONS.values()).index(target)))
        assert consumed == len(data), (name, consumed, len(data))
        for off, size in masks:
            normalized[off:off+size] = bytes(size)
        anchor_mask = bytearray([255]*32)
        for off, size in masks:
            for pos in range(off, min(off+size, 32)):
                anchor_mask[pos] = 0
        anchor = bytes(a & m for a, m in zip(data[:32], anchor_mask))
        lines += [f'static const HfMask masks_{idx}[] = ' + '{' + ','.join(f'{{{o},{s}}}' for o,s in masks) + '};']
        profiles.append('{' + f'"{name}",{len(data)},' + byte_array(anchor.ljust(32,b'\0')) + ',' + byte_array(anchor_mask)
                        + ',' + byte_array(hashlib.sha256(normalized).digest()) + f',masks_{idx},{len(masks)},{int(start in LEAVES)}' + '}')
    assert globals_ and edges
    lines += ['static const HfProfile hf_profiles[HF_PROFILE_COUNT] = {', ',\n'.join(profiles), '};',
              'static const HfReference hf_edges[] = {' + ','.join('{' + ','.join(map(str,e)) + '}' for e in edges) + '};',
              'static const HfReference hf_global_refs[] = {' + ','.join('{' + ','.join(map(str,e)) + '}' for e in globals_) + '};']
    lines += ['static const HfReference hf_capsule_name_ref = {'+','.join(map(str,literal_ref))+'};', 'static const unsigned char hf_capsule_name[] = '+byte_array(literal)+';']
    (ROOT / 'src/address_profile.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print(f'Generated {len(profiles)} full-function fingerprints, {len(edges)} call edges, {len(globals_)} manager references')


if __name__ == '__main__':
    main()

